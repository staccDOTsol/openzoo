#!/usr/bin/env python3
"""
Write-guard PreToolUse hook — auto-installed by Claude IDE.

Two protections for Write/Edit/MultiEdit, enforcing the CLAUDE.md "editing
safety rules" that instructions alone cannot (work has been lost to
shrinking rewrites before; instructions decay over a long context, hooks
do not):

1. Mass-delete guard. Denied ONCE, allowed on identical retry:
     - Write over an existing file >= 400 lines (Write is for new files;
       a faithful full rewrite of a file that size is rarely intentional)
     - Write that shrinks a file by > 30 lines AND to < 75% of its lines
     - Edit/MultiEdit whose net removal exceeds 30 lines
   The first attempt exits 2 with instructions to explain the deletion and
   get user confirmation. Re-running the IDENTICAL call is allowed through
   (approval memory in .claude-ide/.write-guard-state.json, 24h TTL) — a
   deliberate, user-confirmed rewrite costs one retry; a careless one gets
   a speed bump it must explicitly acknowledge.

2. Edit pre-flight. An Edit whose old_string is absent (or not unique) in
   the target file WILL fail after burning a tool call; this hook fails it
   early with the repair recipe (read_exact {path, anchor} / get_section)
   plus a whitespace-normalized closest-match line span, instead of letting
   the model re-guess whitespace from memory. MultiEdit edits are simulated
   sequentially, matching the tool's own semantics.

Fail-open by design: any internal error exits 0 and the tool call proceeds.
If the strike cannot be persisted, the call is allowed (a deny we cannot
remember would deny forever). To disable: remove the PreToolUse
Write|Edit|MultiEdit entry from .claude/settings.json (Project Settings ->
Hooks editor in the IDE).
"""
import hashlib, json, os, sys, tempfile, time

NL = chr(10)
MAX_FILE_BYTES = 8000000
NET_REMOVAL_LIMIT = 30   # lines; mirrors the CLAUDE.md ">30 lines needs confirmation" rule
BIG_WRITE_LINES = 400    # Write over an existing file this big is always a strike
SHRINK_FLOOR = 0.75      # Write keeping < 75% of lines (and removing > 30) is a strike
APPROVAL_TTL = 24 * 3600
STATE_MAX = 300

try:
    data = json.load(sys.stdin)
except Exception:
    sys.exit(0)
if not isinstance(data, dict):
    sys.exit(0)

tool = str(data.get("tool_name") or "")
ti = data.get("tool_input") or {}
path = str(ti.get("file_path") or "")
if not path or tool not in ("Write", "Edit", "MultiEdit"):
    sys.exit(0)

# Paths where big rewrites are routine/generated — not worth a speed bump.
SKIP_SEGS = {"node_modules", ".git", "dist", "build", "target", ".claude-ide",
             "__pycache__", ".next", ".cache", "vendor", "coverage"}
if any(seg in SKIP_SEGS for seg in path.split("/")):
    sys.exit(0)
base = os.path.basename(path)
if base.endswith(".lock") or base in ("package-lock.json", "Cargo.lock", "yarn.lock", "pnpm-lock.yaml"):
    sys.exit(0)
if path.endswith("/.claude/MAP.md"):  # auto-regenerated by the IDE
    sys.exit(0)
tmpdir = os.environ.get("TMPDIR") or "/tmp"
if path.startswith(("/tmp/", "/private/tmp/", "/var/folders/")) or path.startswith(tmpdir):
    sys.exit(0)

old_text = None
try:
    if os.path.isfile(path):
        if os.path.getsize(path) > MAX_FILE_BYTES:
            sys.exit(0)
        with open(path, encoding="utf-8", errors="replace") as f:
            old_text = f.read()
except OSError:
    sys.exit(0)


def deny(msg):
    sys.stderr.write(msg)
    sys.exit(2)


def norm(s):
    return " ".join(s.split())


def closest_span(old_s, text):
    """Best-effort 'you probably meant lines A-B' hint: match the first few
    whitespace-normalized lines of old_string against the file."""
    olines = [norm(l) for l in old_s.splitlines()]
    olines = [l for l in olines if l]
    if not olines:
        return ""
    flines = text.splitlines()
    if len(flines) > 200000:
        return ""
    fnorm = [norm(l) for l in flines]
    probe = olines[: min(len(olines), 4)]
    for i in range(len(fnorm)):
        if fnorm[i] != probe[0]:
            continue
        ok, k = True, i
        for p in probe[1:]:
            k += 1
            while k < len(fnorm) and not fnorm[k]:
                k += 1
            if k >= len(fnorm) or fnorm[k] != p:
                ok = False
                break
        if ok:
            end = min(i + max(len(olines), 1), len(fnorm))
            return "Closest match: lines " + str(i + 1) + "-" + str(end) + " (whitespace differs from your old_string). "
    longest = max(olines, key=len)
    if len(longest) >= 12:
        for i in range(len(fnorm)):
            if longest in fnorm[i]:
                return "Closest match: around line " + str(i + 1) + " (content differs slightly). "
    return ""


def miss_message(old_s, text, which):
    try:
        hint = closest_span(old_s, text)
    except Exception:
        hint = ""
    first = (old_s.splitlines() or [""])[0][:70]
    return (
        "[claude-ide write-guard] This " + tool + which + " would FAIL: old_string is not present in '" + base + "'" + NL
        + "(byte-for-byte check; it starts: " + repr(first) + "). " + hint + NL
        + "Do NOT retype the string from memory and retry. Copy the EXACT bytes first:" + NL
        + "  - MCP: read_exact {path, anchor: <your failed old_string>} -> the verbatim bytes near" + NL
        + "    the closest match (tolerates whitespace drift); build old_string from that." + NL
        + "  - MCP: get_section {path, symbol} for a whole function/class body." + NL
        + "  - Fallback: Bash  sed -n 'START,ENDp' <file>  (quote the path)." + NL
        + "(Read tool output carries line-number prefixes — never reconstruct old_string from it.)" + NL
    )


def ambiguous_message(n, which):
    return (
        "[claude-ide write-guard] This " + tool + which + " would FAIL: old_string matches " + str(n) + " places in '" + base + "'." + NL
        + "Edit requires a UNIQUE match. Either extend old_string with more surrounding lines to pin" + NL
        + "the exact site, or pass replace_all: true to change every occurrence deliberately." + NL
    )


def strike(op, payload, reason, old_n, new_n):
    """Two-strike gate. First identical attempt: record + deny. Second: allow."""
    project = os.environ.get("CLAUDE_PROJECT_DIR") or str(data.get("cwd") or "")
    sid = str(data.get("session_id") or "global")
    digest = hashlib.sha1(payload.encode("utf-8", "replace")).hexdigest()
    key = hashlib.sha1("|".join([sid, op, path, digest]).encode("utf-8", "replace")).hexdigest()
    if project:
        state_path = os.path.join(project, ".claude-ide", ".write-guard-state.json")
    else:
        state_path = os.path.join(tempfile.gettempdir(), "claude-ide-write-guard-state.json")
    state = {}
    try:
        with open(state_path, encoding="utf-8") as f:
            state = json.load(f) or {}
        if not isinstance(state, dict):
            state = {}
    except Exception:
        state = {}
    now = time.time()
    state = {k: t for k, t in state.items() if isinstance(t, (int, float)) and now - t < APPROVAL_TTL}
    if key in state:
        state.pop(key, None)  # consume the approval
        try:
            with open(state_path, "w", encoding="utf-8") as f:
                json.dump(state, f)
        except Exception:
            pass
        return  # identical retry -> allowed
    state[key] = now
    if len(state) > STATE_MAX:
        for k in sorted(state, key=state.get)[: len(state) - STATE_MAX]:
            state.pop(k, None)
    try:
        os.makedirs(os.path.dirname(state_path), exist_ok=True)
        with open(state_path, "w", encoding="utf-8") as f:
            json.dump(state, f)
    except Exception:
        return  # cannot remember the strike -> denying would loop forever; allow
    deny(
        "[claude-ide write-guard] BLOCKED (first attempt): " + reason + NL
        + "Resulting size: " + str(old_n) + " -> " + str(new_n) + " lines." + NL
        + "Per CLAUDE.md editing safety rules: never mass-delete. Explain to the user WHAT will be" + NL
        + "removed and WHY, and wait for their confirmation before removing >30 lines in one step." + NL
        + "  - Prefer several surgical Edits over a rewrite; a cleanup pass must not drop behavior." + NL
        + "  - If the user has ALREADY approved exactly this change, re-run the identical tool call:" + NL
        + "    it will pass (the acknowledgement is remembered for 24h)." + NL
        + "To disable this guard: remove the PreToolUse Write|Edit|MultiEdit entry in .claude/settings.json." + NL
    )


if tool == "Write":
    if old_text is None:
        sys.exit(0)  # brand-new file — nothing to lose
    new_text = str(ti.get("content") or "")
    old_n, new_n = len(old_text.splitlines()), len(new_text.splitlines())
    removed = old_n - new_n
    if old_n >= BIG_WRITE_LINES:
        strike("write-big", new_text,
               "Write would OVERWRITE '" + base + "' (" + str(old_n) + " lines) wholesale. Write is for NEW files; use surgical Edits on a file this size.",
               old_n, new_n)
    elif removed > NET_REMOVAL_LIMIT and new_n < old_n * SHRINK_FLOOR:
        strike("write-shrink", new_text,
               "Write would SHRINK '" + base + "' from " + str(old_n) + " to " + str(new_n) + " lines (-" + str(removed) + ").",
               old_n, new_n)
    sys.exit(0)

# Edit / MultiEdit
if old_text is None:
    sys.exit(0)  # let the tool produce its own missing-file error
edits = [ti] if tool == "Edit" else (ti.get("edits") if isinstance(ti.get("edits"), list) else [])
if not edits:
    sys.exit(0)

work = old_text
for i, e in enumerate(edits):
    if not isinstance(e, dict):
        sys.exit(0)
    old_s = str(e.get("old_string") or "")
    new_s = str(e.get("new_string") or "")
    if not old_s:
        continue  # file-create form; the tool validates it
    which = " (edit #" + str(i + 1) + " of " + str(len(edits)) + ")" if len(edits) > 1 else ""
    n = work.count(old_s)
    if n == 0:
        deny(miss_message(old_s, work, which))
    if n > 1 and not e.get("replace_all"):
        deny(ambiguous_message(n, which))
    work = work.replace(old_s, new_s) if e.get("replace_all") else work.replace(old_s, new_s, 1)

removed = len(old_text.splitlines()) - len(work.splitlines())
if removed > NET_REMOVAL_LIMIT:
    payload = json.dumps([[str(e.get("old_string") or ""), str(e.get("new_string") or "")] for e in edits])
    strike("edit-delete", payload,
           "This " + tool + " removes a net " + str(removed) + " lines from '" + base + "'.",
           len(old_text.splitlines()), len(work.splitlines()))
sys.exit(0)
